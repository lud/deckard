// @ts-check
// Emits the generated Marp file (§4). Two rules shape everything here: spot
// directives (`_`-prefixed) so per-slide layout never inherits forward, and a
// presenter-note comment kept separate from the directive comment so a note is
// never read as a directive.
import { findSection, metaValue } from './deck-parse.mjs'

/**
 * Promote in-slide headings two levels, matching the title's H3 → H1 shift
 * (§2.2). Fenced lines pass through untouched, so a `#` comment in a shell
 * snippet stays a comment.
 * @param {import('./deck-parse.mjs').Line} entry
 */
function promote(entry) {
  if (entry.fenced) return entry.text
  return entry.text.replace(/^(#{4,6})(\s)/, (_, hashes, space) => '#'.repeat(hashes.length - 2) + space)
}

/** @param {import('./deck-parse.mjs').Line[]} lines */
function trimBlank(lines) {
  let start = 0
  let end = lines.length
  while (start < end && lines[start].text.trim() === '') start++
  while (end > start && lines[end - 1].text.trim() === '') end--
  return lines.slice(start, end)
}

/**
 * Spot directives for one slide: the named layout hint plus every `marp:`
 * passthrough, which carries a raw directive verbatim (§2.3).
 * @param {import('./deck-parse.mjs').Slide} slide
 */
function directives(slide) {
  const out = []
  const layout = metaValue(slide, 'layout')
  if (layout) out.push(`_class: ${layout}`)
  for (const entry of slide.metadata) {
    if (entry.key !== 'marp') continue
    out.push(entry.value.startsWith('_') ? entry.value : `_${entry.value}`)
  }
  return out
}

/**
 * Asset paths pass through exactly as the author wrote them: the render is
 * written at the project root, where source-relative references resolve.
 * @param {{ title: string | null, slides: import('./deck-parse.mjs').Slide[] }} deck
 * @param {{ source: string }} options
 */
export function emitMarp(deck, { source }) {
  const out = [
    '---',
    // A YAML comment, not an HTML one: an HTML comment here would be
    // collected as slide 1's presenter note (§5.1).
    `# Generated by Deckard from ${source}. Edit that file and rebuild.`,
    'marp: true',
  ]
  if (deck.title) out.push(`title: ${JSON.stringify(deck.title)}`)
  out.push('---', '', '')

  const rendered = deck.slides.map((slide) => {
    const parts = []
    const spot = directives(slide)
    if (spot.length === 1) parts.push(`<!-- ${spot[0]} -->`)
    else if (spot.length > 1) parts.push(['<!--', ...spot, '-->'].join('\n'))

    parts.push(`# ${slide.title}`)

    const body = trimBlank(slide.body).map(promote)
    if (body.length > 0) parts.push(body.join('\n'))

    // `deck: Media` holds pre-media intent and `deck: Knowledge` the research
    // trail; produced assets already live in the body, so neither is emitted.
    const notes = findSection(slide, 'notes')
    if (notes) {
      const lines = trimBlank(notes.lines).map((entry) => entry.text)
      if (lines.length > 0) parts.push(['<!--', ...lines, '-->'].join('\n'))
    }

    return parts.join('\n\n')
  })

  return `${out.join('\n')}${rendered.join('\n\n---\n\n')}\n`
}
